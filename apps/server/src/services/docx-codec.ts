import { posix } from "node:path";
import { unzipSync, zipSync, type Zippable } from "fflate";
import {
  InkadeError,
  markdownToDocxFiles,
  parseDocxPackageFiles,
  type MarkdownToDocxOptions,
  type ParsedDocxDocument,
} from "@inkade/core";

const DEFAULT_MAX_DOCX_ENTRIES = 2000;
const DEFAULT_MAX_DOCX_BYTES = 50 * 1024 * 1024;

function isSafeDocxEntryPath(rawPath: string): boolean {
  const norm = rawPath.replace(/\\/g, "/").trim();
  if (!norm || norm.startsWith("/") || norm.includes("\0")) return false;
  if (norm.split("/").some((seg) => seg === "..")) return false;
  if (norm.startsWith("__MACOSX/") || norm.endsWith("/")) return false;
  return true;
}

/**
 * Compresses an OOXML file map generated by `@inkade/core` into a `.docx` binary archive via `fflate` (MIT).
 */
export function encodeDocxPackage(files: Readonly<Record<string, Uint8Array>>): Uint8Array {
  const zippable: Zippable = {};
  for (const [path, bytes] of Object.entries(files)) {
    zippable[path] = bytes;
  }
  return zipSync(zippable);
}

/**
 * Extracts and validates a `.docx` ZIP archive safely using `fflate`, guarding against zip bombs and path traversal.
 */
export function decodeDocxArchive(
  bytes: Uint8Array,
  options?: {
    readonly maxEntries?: number | undefined;
    readonly maxTotalBytes?: number | undefined;
  },
): Map<string, Uint8Array> {
  if (bytes.byteLength < 4 || bytes[0] !== 0x50 || bytes[1] !== 0x4b) {
    throw new InkadeError("VALIDATION_ERROR", "Invalid DOCX file: expected ZIP archive signature");
  }

  let rawMap: Record<string, Uint8Array>;
  try {
    rawMap = unzipSync(bytes);
  } catch (err) {
    throw new InkadeError(
      "VALIDATION_ERROR",
      `Invalid DOCX archive: ${err instanceof Error ? err.message : String(err)}`,
    );
  }

  const maxEntries = options?.maxEntries ?? DEFAULT_MAX_DOCX_ENTRIES;
  const maxTotalBytes = options?.maxTotalBytes ?? DEFAULT_MAX_DOCX_BYTES;
  const keys = Object.keys(rawMap);
  if (keys.length > maxEntries) {
    throw new InkadeError("VALIDATION_ERROR", `DOCX archive exceeds maximum ${maxEntries} entries`);
  }

  const files = new Map<string, Uint8Array>();
  let totalBytes = 0;
  for (const key of keys.sort()) {
    if (!isSafeDocxEntryPath(key)) continue;
    const data = rawMap[key];
    if (!data) continue;
    totalBytes += data.byteLength;
    if (totalBytes > maxTotalBytes) {
      throw new InkadeError(
        "VALIDATION_ERROR",
        `DOCX uncompressed size exceeds ${maxTotalBytes} bytes`,
      );
    }
    files.set(posix.normalize(key.replace(/\\/g, "/")), data);
  }

  return files;
}

/**
 * Convenience codec helper converting `.docx` bytes directly into parsed Markdown + extracted images.
 */
export function parseDocxBytesToDocument(
  bytes: Uint8Array,
  filename?: string,
): ParsedDocxDocument {
  const files = decodeDocxArchive(bytes);
  return parseDocxPackageFiles(files, { filename });
}

/**
 * Convenience codec helper converting Markdown + optional embedded media directly into `.docx` bytes.
 */
export function buildDocxBytesFromMarkdown(options: MarkdownToDocxOptions): {
  readonly bytes: Uint8Array;
  readonly mediaCount: number;
  readonly hyperlinkCount: number;
} {
  const pkg = markdownToDocxFiles(options);
  return {
    bytes: encodeDocxPackage(pkg.files),
    mediaCount: pkg.mediaCount,
    hyperlinkCount: pkg.hyperlinkCount,
  };
}
